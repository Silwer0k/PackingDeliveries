package ru.hofftech.packingdeliveries.service.processors;

import java.util.List;

/**
 * Интерфейс процессора команд, определяющий стандарт выполнения бизнес-логики.
 * <p>
 * Все классы, реализующие этот интерфейс, инкапсулируют конкретную задачу
 * и предоставляют единый механизм для запуска процесса и проверки его статуса.
 */
public interface CommandProcessor {
    /**
     * Запускает выполнение бизнес-логики команды.
     * <p>
     * Вся работа по обработке данных, взаимодействию с репозиториями
     * или файлами должна происходить внутри этого метода.
     */
    void doProcess();

    /**
     * Проверяет, была ли команда выполнена успешно.
     *
     * @return {@code true}, если процесс завершился без критических ошибок;
     *         {@code false} в случае неудачи.
     */
    boolean isSuccess();

    /**
     * Возвращает список текстовых описаний ошибок, возникших в ходе выполнения.
     *
     * @return список строк с сообщениями об ошибках (пустой список, если ошибок нет).
     */
    List<String> getProcessErrors();
}
